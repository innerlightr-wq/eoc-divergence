r,S,C = eoc.residues(ds)
print(f"  confined (2^S_n <= 3^n for all n): {eoc.confined(ds)}")
print(f"  S_60 = {S[-1]}   d-prefix = {ds[:18]}")
print(f"  {'n':>4} {'S_n':>5} {'r_n (low 40 bits, hex)':>26} {'r_n == r_{n-1}?':>16}")
